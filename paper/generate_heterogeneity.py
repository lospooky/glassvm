#!/usr/bin/env python3
"""Render the qualitative machine table from the checked-in JSON manifest."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "heterogeneity.json"
OUTPUT = ROOT / "generated" / "heterogeneity_table.tex"


def escape_latex(value: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(character, character) for character in value)


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    columns = data["columns"]
    if len(columns) != 3 or not data["rows"]:
        raise ValueError("heterogeneity table must have three columns and at least one row")
    if any(len(row) != len(columns) for row in data["rows"]):
        raise ValueError("each heterogeneity row must match the column count")

    lines = [
        "% Generated by generate_heterogeneity.py; edit heterogeneity.json instead.",
        r"\begin{tabular}{p{0.14\linewidth} p{0.28\linewidth} p{0.48\linewidth}}",
        r"\toprule",
        " & ".join(r"\textbf{" + escape_latex(value) + "}" for value in columns) + r" \\",
        r"\midrule",
    ]
    for row in data["rows"]:
        lines.append(" & ".join(escape_latex(value) for value in row) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
